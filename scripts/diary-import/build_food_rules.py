#!/usr/bin/env python3
"""Turns the Quy_tac_nhan_xet sheet of the diary workbook into src/feedback/rulesData.ts (the app's food comment rules).

    python3 scripts/diary-import/build_food_rules.py Input/NhatKy_FitJourney.xlsx src/feedback/rulesData.ts
"""
import sys

import openpyxl

KIND = {'Cần thay': 'replace', 'Lưu ý': 'note', 'Tốt': 'good'}


def ts(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'") + "'"


def cell(v):
    return str(v).strip() if v is not None else ''


def main(src, dest):
    ws = openpyxl.load_workbook(src, data_only=True)['Quy_tac_nhan_xet']
    rules = []
    for r in ws.iter_rows(min_row=5, values_only=True):
        keyword = cell(r[0]).lower()
        if not keyword:
            continue
        kind = KIND[cell(r[2])]
        repeat = int(r[5]) if isinstance(r[5], (int, float)) else 0
        rules.append((keyword, cell(r[1]), kind, cell(r[3]), cell(r[4]), repeat, cell(r[6]), cell(r[7])))
    assert len(rules) > 60, 'rule table looks empty'
    assert len({r[0] for r in rules}) == len(rules), 'duplicate keywords'
    for keyword, short, kind, why, replace, repeat, hint, short_replace in rules:
        assert short and why, f'rule {keyword} needs a name and a reason'
        if kind != 'good':
            assert replace and short_replace, f'rule {keyword} needs a replacement'

    out = [
        "import type { FoodRule } from './types';",
        '',
        '// Generated by scripts/diary-import/build_food_rules.py from the Quy_tac_nhan_xet sheet. A rule fires when its keyword',
        '// (lower case) appears in a food description. `repeatAt` is how many times in 3 days counts as a repeat (0 = never).',
        'export const FOOD_RULES: FoodRule[] = [',
    ]
    for keyword, short, kind, why, replace, repeat, hint, short_replace in rules:
        out.append(
            '  { ' + ', '.join([f'keyword: {ts(keyword)}', f'short: {ts(short)}', f'kind: {ts(kind)}', f'why: {ts(why)}', f'replaceWith: {ts(replace)}',
                                f'repeatAt: {repeat}', f'repeatHint: {ts(hint)}', f'shortReplace: {ts(short_replace)}']) + ' },'
        )
    out += ['];', '']
    open(dest, 'w').write('\n'.join(out))
    print(f'{len(rules)} rules -> {dest}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
