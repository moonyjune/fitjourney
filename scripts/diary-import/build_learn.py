#!/usr/bin/env python3
"""Turns the Ly_thuyet and Thay_the_snack sheets of the diary workbook into the app's reading content.

    python3 scripts/diary-import/build_learn.py Input/NhatKy_FitJourney.xlsx src/learn

Writes src/learn/topicsData.ts (the general explanations) and src/learn/snackData.ts (the craving swaps). Both are general
nutrition text and are committed with the app. The sheet's "Ap dung cho ban" column quotes the owner's own meals, weights and
dates, so it is NOT written here: build_seed.py puts it in diary-import.json (key learnNotes) and the app loads it from there.
"""
import json
import re
import sys

import openpyxl

SECTIONS = {'NỀN TẢNG': 'basics', 'ĂN GÌ – VÌ SAO': 'food', 'THÓI QUEN – VÌ SAO': 'habit', 'GOUT & VẬN ĐỘNG': 'gout'}
EVIDENCE = {'Mạnh': 'strong', 'Trung bình': 'medium', 'Hạn chế': 'limited', 'Hạn chế – Trung bình': 'limited'}
# The sheets point at each other by worksheet name; in the app those places have other names.
SHEET_NAMES = [
    ('Can_nang', 'Phân tích → Tổng quan'),
    ('Phan_tich', 'Phân tích'),
    ('Thay_the_snack', 'Kiến thức → Thay snack'),
    ('Bai_tap', 'Phân tích → Vận động'),
    ('Tong_hop_tuan', 'Phân tích → Tuần/tháng'),
    ('Tong_hop_ngay', 'Phân tích → Nhận xét'),
    ('CSDL_mon_an', 'Hồ sơ → Cơ sở dữ liệu món ăn'),
    ('Quy_tac_nhan_xet', 'Phân tích → Nhận xét'),
    ('Chi_tiet_bua_an', 'nhật ký ăn uống'),
    ('Thong_so', 'Hồ sơ → Giới hạn'),
]


def localize(text):
    for name, replacement in SHEET_NAMES:
        text = re.sub(rf'(?:sheet\s+)?{name}', replacement, text, flags=re.IGNORECASE)
    leftover = re.findall(r'[A-Za-z]+_[A-Za-z_]+|\bsheet\b', text, flags=re.IGNORECASE)
    assert not leftover, f'unmapped sheet reference {leftover} in: {text[:80]}'
    return text


def ts(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n') + "'"


def read_topics(wb):
    topics, notes, section = [], {}, None
    for r in wb['Ly_thuyet'].iter_rows(min_row=4, values_only=True):
        if r[0] in SECTIONS and r[1] is None:
            section = SECTIONS[r[0]]
            continue
        if not (r[0] and str(r[0]).isdigit()):
            continue
        n = int(r[0])
        points = [re.sub(r'^•\s*', '', p).strip() for p in str(r[2]).split('\n') if p.strip()]
        evidence = EVIDENCE[str(r[4]).strip()]
        topics.append({'id': n, 'section': section, 'title': str(r[1]).strip(), 'points': [localize(p) for p in points], 'evidence': evidence})
        if r[3]:
            notes[str(n)] = localize(str(r[3]).strip())
    assert [t['id'] for t in topics] == list(range(1, len(topics) + 1)), 'topic numbers must run 1..N'
    assert len(topics) >= 20, 'topic table looks empty'
    return topics, notes


def read_snacks(wb):
    out = []
    for r in wb['Thay_the_snack'].iter_rows(min_row=4, values_only=True):
        if not r[0] or not isinstance(r[3], (int, float)):
            continue
        out.append({'id': len(out) + 1, 'craving': str(r[0]).strip(), 'swap': str(r[1]).strip(), 'portion': str(r[2]).strip(), 'kcal': int(r[3]),
                    'note': localize(str(r[4]).strip()) if r[4] else ''})
    assert len(out) >= 15, 'snack table looks empty'
    return out


def write_topics(path, topics):
    lines = ["import type { LearnTopic } from './types';", '',
             '// Generated by scripts/diary-import/build_learn.py from the Ly_thuyet sheet. General nutrition knowledge, not medical advice.',
             'export const LEARN_TOPICS: LearnTopic[] = [']
    for t in topics:
        pts = ', '.join(ts(p) for p in t['points'])
        lines.append(f"  {{ id: {t['id']}, section: {ts(t['section'])}, title: {ts(t['title'])}, evidence: {ts(t['evidence'])}, points: [{pts}] }},")
    lines += ['];', '']
    open(path, 'w').write('\n'.join(lines))


def write_snacks(path, snacks):
    lines = ["import type { SnackSwap } from './types';", '',
             '// Generated by scripts/diary-import/build_learn.py from the Thay_the_snack sheet. Kcal is an estimate for the suggested portion.',
             'export const SNACK_SWAPS: SnackSwap[] = [']
    for s in snacks:
        fields = [f"id: {s['id']}", f"craving: {ts(s['craving'])}", f"swap: {ts(s['swap'])}", f"portion: {ts(s['portion'])}", f"kcal: {s['kcal']}"]
        if s['note']:
            fields.append(f"note: {ts(s['note'])}")
        lines.append('  { ' + ', '.join(fields) + ' },')
    lines += ['];', '']
    open(path, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    wb = openpyxl.load_workbook(sys.argv[1], data_only=True)
    topics, notes = read_topics(wb)
    snacks = read_snacks(wb)
    write_topics(f'{sys.argv[2]}/topicsData.ts', topics)
    write_snacks(f'{sys.argv[2]}/snackData.ts', snacks)
    print(f'{len(topics)} topics, {len(snacks)} snack swaps ({len(notes)} personal notes are not written here)')
    print(json.dumps({'notes': len(notes)}))
