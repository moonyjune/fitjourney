#!/usr/bin/env python3
"""Turns the CSDL_mon_an sheet of the diary workbook into src/food/foodData.ts (the app's built-in food table).

    python3 scripts/diary-import/build_food_db.py Input/NhatKy_FitJourney.xlsx src/food/foodData.ts

Every value is per 100 g (or per 100 ml) of the edible part, as in the sheet. The sheet's own purine level column is
checked against the thresholds the app uses, so a changed sheet fails loudly instead of shipping inconsistent labels.
"""
import re
import sys

import openpyxl

GROUPS = {
    'Trứng & sữa': 'eggDairy', 'Đạm thực vật': 'plantProtein', 'Gia cầm': 'poultry', 'Thịt đỏ': 'redMeat',
    'Hải sản': 'seafood', 'Chế biến sẵn': 'processed', 'Tinh bột': 'starch', 'Món nước': 'soup', 'Rau': 'vegetable',
    'Trái cây': 'fruit', 'Hạt': 'nuts', 'Gia vị': 'seasoning', 'Đồ uống': 'drink', 'Đồ ngọt': 'sweet', 'Đồ vặt': 'snack',
}
CONFIDENCE = {'Cao': 'high', 'Trung bình': 'medium', 'Thấp': 'low'}
LEVEL = {'Thấp': 'low', 'Trung bình': 'medium', 'Cao': 'high'}


def purine_level(per100):
    return 'low' if per100 < 50 else 'medium' if per100 < 160 else 'high'


def num(v):
    r = round(float(v), 4)
    return int(r) if r == int(r) else r


def ts(s):
    return "'" + str(s).replace('\\', '\\\\').replace("'", "\\'") + "'"


def main(src, dest):
    ws = openpyxl.load_workbook(src, data_only=True)['CSDL_mon_an']
    rows = []
    for r in ws.iter_rows(min_row=5, values_only=True):
        if not r[0] or r[1] not in GROUPS:
            continue
        name, group, unit, unit_g = str(r[0]).strip(), GROUPS[r[1]], str(r[2]).strip(), num(r[3])
        kcal, protein, purine, sugar, sodium = (num(r[i]) for i in range(4, 9))
        level = LEVEL[r[9]]
        assert level == purine_level(purine), f'purine level of {name}: sheet says {r[9]}, thresholds say {purine_level(purine)}'
        note = (str(r[12]).strip() if r[12] else '')
        rows.append((name, group, unit, unit_g, kcal, protein, purine, sugar, sodium, note, CONFIDENCE[r[13]]))
    assert len(rows) > 100, 'food table looks empty'
    assert len({r[0] for r in rows}) == len(rows), 'duplicate food names'

    out = [
        "import type { FoodEntry } from './types';",
        '',
        '// Generated by scripts/diary-import/build_food_db.py from the CSDL_mon_an sheet. Values are per 100 g (or 100 ml) of the',
        '// edible part, cooked where the name says so. They are approximations from common food tables and labels, not medical data.',
        'export const BUILT_IN_FOODS: FoodEntry[] = [',
    ]
    for i, (name, group, unit, unit_g, kcal, protein, purine, sugar, sodium, note, conf) in enumerate(rows):
        fields = [f"id: 'f{i + 1:03d}'", f'name: {ts(name)}', f'group: {ts(group)}', f'unit: {ts(unit)}', f'unitG: {unit_g}',
                  f'kcal: {kcal}', f'proteinG: {protein}', f'purineMg: {purine}', f'sugarG: {sugar}', f'sodiumMg: {sodium}']
        if note:
            fields.append(f'note: {ts(note)}')
        fields.append(f'confidence: {ts(conf)}')
        out.append('  { ' + ', '.join(fields) + ' },')
    out += ['];', '']
    open(dest, 'w').write('\n'.join(out))
    print(f'{len(rows)} foods -> {dest}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
