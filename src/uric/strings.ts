export function formatUricText(language: 'vi' | 'en', key: UricKey, params?: Record<string, string | number>): string {
  const template = (language === 'en' ? en : vi)[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function useUricText() {
  const language = useSettingsStore((s) => s.language);
  return useCallback((key: UricKey, params?: Record<string, string | number>) => formatUricText(language, key, params), [language]);
}
