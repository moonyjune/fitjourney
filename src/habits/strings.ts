export function formatHabitText(language: 'vi' | 'en', key: HabitKey, params?: Record<string, string | number>): string {
  const template = (language === 'en' ? en : vi)[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function useHabitText() {
  const language = useSettingsStore((s) => s.language);
  return useCallback((key: HabitKey, params?: Record<string, string | number>) => formatHabitText(language, key, params), [language]);
}
