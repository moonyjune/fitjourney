export function formatInsightsText(language: 'vi' | 'en', key: InsightsKey, params?: Record<string, string | number>): string {
  const template = (language === 'en' ? en : vi)[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function useInsightsText() {
  const language = useSettingsStore((s) => s.language);
  return useCallback(
    (key: InsightsKey, params?: Record<string, string | number>) => formatInsightsText(language, key, params),
    [language]
  );
}
