export function formatGameText(language: 'vi' | 'en', key: GameKey, params?: Record<string, string | number>): string {
  const template = (language === 'en' ? en : vi)[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

export function useGameText() {
  const language = useSettingsStore((s) => s.language);
  return useCallback(
    (key: GameKey, params?: Record<string, string | number>) => formatGameText(language, key, params),
    [language]
  );
}
